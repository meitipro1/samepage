#!/usr/bin/env python3
"""
Generate the docs pages and site data that are copies of the contract and its records.

    python scripts/gen_docs.py           # write the files
    python scripts/gen_docs.py --check   # exit 1 if any file differs from what would be written

A method cannot exist in the code and be missing from the docs, and the judge
prompt on the site cannot drift from the one validators read, because both are
written from contracts/samepage.py by this script, and a test runs --check.

Writes:
  web/content/docs/reference/contract.mdx    every public method, from the source
  web/content/docs/reference/errors.mdx      every refusal sentence, from the source
  web/content/docs/reference/addresses.mdx   the deployment, from contracts/FROZEN.json
  web/content/docs/reference/hashing.mdx     the hashing rules and the shared vectors, from tests/vectors.json
  web/content/docs/more/judge-prompt.mdx     the judge prompt, word for word
  web/content/docs/more/evaluation.mdx       the golden run, from eval/results.json
  web/lib/contract.generated.json            limits, labels and the prompt, for the site
and refreshes every `{/* include: path */}` code sample in the docs from the file it names.
"""

from __future__ import annotations

import ast
import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "contracts" / "samepage.py"
DOCS = ROOT / "web" / "content" / "docs"
REPO = "https://github.com/meitipro1/samepage/blob/main"

HEADER = "{/* Generated by scripts/gen_docs.py from contracts/samepage.py. Do not edit by hand. */}\n\n"


def load():
    source = CONTRACT.read_text(encoding="utf-8")
    return source, ast.parse(source)


def constant(tree: ast.Module, name: str):
    for node in tree.body:
        if isinstance(node, ast.Assign) and ast.unparse(node.targets[0]) == name:
            try:
                return ast.literal_eval(node.value)
            except ValueError:
                return ast.unparse(node.value)
    raise KeyError(name)


def contract_class(tree: ast.Module) -> ast.ClassDef:
    return next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "Samepage")


def kind_of(node: ast.FunctionDef) -> str:
    for deco in node.decorator_list:
        text = ast.unparse(deco)
        if text == "gl.public.write":
            return "write"
        if text == "gl.public.write.payable":
            return "payable"
        if text == "gl.public.view":
            return "view"
    return ""


def mdx_text(text: str) -> str:
    """Plain prose into MDX: braces and angle brackets would be read as code."""
    return text.replace("{", "&#123;").replace("}", "&#125;").replace("<", "&lt;").replace(">", "&gt;")


def signature(node: ast.FunctionDef) -> str:
    args = ", ".join(f"{a.arg}: {ast.unparse(a.annotation)}" for a in node.args.args[1:])
    returns = ast.unparse(node.returns) if node.returns else "None"
    return f"{node.name}({args}) -> {returns}"


def methods(tree: ast.Module) -> list[dict]:
    out = []
    for node in contract_class(tree).body:
        if isinstance(node, ast.FunctionDef) and kind_of(node):
            doc = ast.get_docstring(node) or ""
            out.append(
                {
                    "name": node.name,
                    "kind": kind_of(node),
                    "signature": signature(node),
                    "args": [{"name": a.arg, "type": ast.unparse(a.annotation)} for a in node.args.args[1:]],
                    "returns": ast.unparse(node.returns) if node.returns else "None",
                    "doc": " ".join(doc.split()),
                    "line": node.lineno,
                }
            )
    return out


def refusals(tree: ast.Module) -> list[dict]:
    """Every UserError sentence, with the function it can come from. Dynamic parts read as '…'."""

    def text_of(expr: ast.AST) -> tuple[str, str]:
        parts: list[str] = []

        def walk(e: ast.AST) -> None:
            if isinstance(e, ast.BinOp) and isinstance(e.op, ast.Add):
                walk(e.left)
                walk(e.right)
            elif isinstance(e, ast.Constant) and isinstance(e.value, str):
                parts.append(e.value)
            elif isinstance(e, ast.Name) and e.id in ("E", "L"):
                parts.append("\x00" + e.id)
            else:
                parts.append("…")

        walk(expr)
        prefix = parts[0][1:] if parts and parts[0].startswith("\x00") else ""
        body = "".join(p for p in parts if not p.startswith("\x00"))
        return prefix, body

    owner: dict[int, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef):
            for inner in ast.walk(node):
                if hasattr(inner, "lineno"):
                    owner.setdefault(inner.lineno, node.name)
    rows: dict[tuple, dict] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and ast.unparse(node.func) == "gl.vm.UserError" and node.args:
            prefix, body = text_of(node.args[0])
            key = (prefix, body)
            where = owner.get(node.lineno, "")
            row = rows.setdefault(key, {"prefix": prefix, "text": body, "where": []})
            if where and where not in row["where"]:
                row["where"].append(where)
    return sorted(rows.values(), key=lambda r: (r["prefix"], r["text"]))


def build() -> dict[pathlib.Path, str]:
    source, tree = load()
    judge = constant(tree, "JUDGE")
    judge_sha = hashlib.sha256(judge.encode("utf-8")).hexdigest()
    shown = judge.replace("{{", "{").replace("}}", "}")
    listed = methods(tree)
    errors = refusals(tree)
    files: dict[pathlib.Path, str] = {}

    # -- contract reference --------------------------------------------------
    kinds = {"write": "write", "payable": "write, payable", "view": "view"}
    lines = [
        "---",
        "title: Contract reference",
        "description: Every public method of contracts/samepage.py, generated from the source.",
        "---",
        "",
        HEADER.strip(),
        "",
        f"One contract, {len(listed)} methods: {sum(1 for m in listed if m['kind'] != 'view')} writes and "
        f"{sum(1 for m in listed if m['kind'] == 'view')} views. This page is written from the contract source by "
        "`scripts/gen_docs.py`, and a test fails if the two drift, so a method cannot exist in code and be missing here.",
        "",
        "Views return JSON text. An unknown page reads as `{\"found\": false}` rather than an error, because a view "
        "that raises reaches a client only as \"execution failed\". Amounts are wei, as decimal strings; times are unix "
        "seconds of the transaction that set them. Views never read the clock: a reader compares `step_end` with the "
        "time now to know whether the current step's window is still open.",
        "",
        "| Method | Kind | What it does |",
        "|---|---|---|",
    ]
    for m in listed:
        first = mdx_text(m["doc"].split(". ")[0].rstrip(".")) + "."
        lines.append(f"| [`{m['name']}`](#{m['name'].replace('_', '-')}) | {kinds[m['kind']]} | {first} |")
    lines.append("")
    for m in listed:
        lines += [
            f"## {m['name']}",
            "",
            "```python",
            m["signature"],
            "```",
            "",
            f"**{kinds[m['kind']].capitalize()}.** {mdx_text(m['doc'])}",
            "",
        ]
        own = [e for e in errors if m["name"] in e["where"]]
        if own:
            lines.append("Refusals raised in the method itself (shared checks add their own, listed on the Errors page):")
            lines.append("")
            for e in own:
                lines.append(f"- `[{'EXPECTED' if e['prefix'] == 'E' else 'LLM_ERROR'}] {e['text']}`")
            lines.append("")
        lines.append(f"[Source, line {m['line']}]({REPO}/contracts/samepage.py#L{m['line']})")
        lines.append("")
    files[DOCS / "reference" / "contract.mdx"] = "\n".join(lines)

    # -- errors --------------------------------------------------------------
    lines = [
        "---",
        "title: Errors",
        "description: Every refusal the contract can raise, generated from the source.",
        "---",
        "",
        HEADER.strip(),
        "",
        "A refused write still reaches consensus: validators agree the refusal is the right result, and the transaction "
        "reads ACCEPTED. The site counts a write as done only when the status is ACCEPTED or FINALIZED **and** the "
        "execution returned; otherwise it shows the sentence below, which the transaction carries in its result payload. "
        "A refused write keeps nothing it was sent: a join with the wrong deposit leaves the value with the sender.",
        "",
        "`[EXPECTED]` refusals are deterministic and identical on every validator. `[LLM_ERROR]` means the judge's "
        "answer could not be read as six statuses, even after one retry; validators then disagree on purpose, so the "
        "round rotates to a committee that can answer, and nothing defaults to a status.",
        "",
        "| Refusal | Raised in |",
        "|---|---|",
    ]
    for e in errors:
        tag = "EXPECTED" if e["prefix"] == "E" else "LLM_ERROR"
        where = ", ".join(f"`{w}`" for w in e["where"])
        lines.append(f"| `[{tag}] {e['text']}` | {where} |")
    lines.append("")
    files[DOCS / "reference" / "errors.mdx"] = "\n".join(lines)

    # -- the prompt ----------------------------------------------------------
    lines = [
        "---",
        "title: The judge prompt, word for word",
        "description: The prompt every validator reads, copied from the contract.",
        "---",
        "",
        HEADER.strip(),
        "",
        "This is the `JUDGE` constant in `contracts/samepage.py`, section 3 of the build spec word for word. The title and "
        "the two accounts are each fenced before they are inserted: every `<` becomes `(` and every `>` becomes `)`, so no "
        "account can write `>>>` to close its own block and open a forged one. The title is flattened to one line first. "
        "Storage keeps what was written.",
        "",
        "```text",
        shown,
        "```",
        "",
        f"SHA-256 of the constant: `{judge_sha}`.",
        "",
        "## Both orders, on every node",
        "",
        "A model that compares two texts can lean towards whichever comes first, and every validator would lean the same "
        "way, so consensus alone cannot catch it. Each node therefore asks twice inside one block: once with the opener's "
        "account as A, once with the counterparty's as A. Where the two orders give the same status for a term, that is the "
        "status. Where they do not, the term is stored as `DIFFER`: a term the model reads one way in one order and another "
        "way in the other is a term the two sides should talk about. The uncertainty is settled in the value, before "
        "anything is compared.",
        "",
        "## How validators agree",
        "",
        "Each validator asks in both orders itself and agrees only when its six statuses are exactly the leader's. There is "
        "no tolerance: `MATCH` against `ABSENT` is a disagreement like any other. The one-line notes are the leader's, "
        "stored as a reading aid on the result page; they are never compared and never signed.",
        "",
        "An answer the contract cannot read as six statuses is asked once more, then fails the round. It never becomes a "
        "status. A round where validators disagree stores nothing: the page stays on its check step, and anyone may send "
        "`check` again until the window closes. After that, `no_show` closes the page `NOT_AGREED` with both deposits back, "
        "because nobody was absent.",
        "",
        "## The verdict is code",
        "",
        "```python",
        "differ = [t for t in TERMS if status[t] == \"DIFFER\"]",
        "gaps = [t for t in REQUIRED if status[t] == \"ABSENT\"]   # amount, deliverable, deadline",
        "verdict = \"DIFFERENT\" if differ else (\"GAPS\" if gaps else \"SAME_PAGE\")",
        "```",
        "",
        "The prompt never mentions a verdict, deposits, rounds, windows or signatures, and a test fails if it does.",
        "",
    ]
    files[DOCS / "more" / "judge-prompt.mdx"] = "\n".join(lines)

    # -- site data -----------------------------------------------------------
    data = {
        "source": "contracts/samepage.py",
        "judge": shown,
        "judgeSha256": judge_sha,
        "terms": list(constant(tree, "TERMS")),
        "required": list(constant(tree, "REQUIRED")),
        "statuses": list(constant(tree, "STATUSES")),
        "verdicts": list(constant(tree, "VERDICTS")),
        "steps": list(constant(tree, "STEPS")),
        "limits": {
            "title": constant(tree, "MAX_TITLE"),
            "account": constant(tree, "MAX_ACCOUNT"),
            "rounds": constant(tree, "MAX_ROUNDS"),
            "minWindow": constant(tree, "MIN_WINDOW"),
            "maxWindow": constant(tree, "MAX_WINDOW"),
            "minSalt": constant(tree, "MIN_SALT"),
            "maxSalt": constant(tree, "MAX_SALT"),
            "page": constant(tree, "MAX_PAGE"),
        },
        "methods": [{k: m[k] for k in ("name", "kind", "signature", "doc")} for m in listed],
    }
    files[ROOT / "web" / "lib" / "contract.generated.json"] = json.dumps(data, indent=2, ensure_ascii=False) + "\n"

    files[DOCS / "more" / "evaluation.mdx"] = evaluation_page()
    files[DOCS / "reference" / "addresses.mdx"] = addresses_page()
    files[DOCS / "reference" / "hashing.mdx"] = hashing_page()
    files.update(synced_includes())
    return files


