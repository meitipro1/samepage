def hashing_page() -> str:
    vectors = json.loads((ROOT / "tests" / "vectors.json").read_text(encoding="utf-8"))
    lines = [
        "---",
        "title: Hashing, with test vectors",
        "description: How a seal is made, byte for byte, and the vectors the contract and the site are tested against.",
        "---",
        "",
        "{/* Generated by scripts/gen_docs.py from tests/vectors.json. Do not edit by hand. */}",
        "",
        "A seal is SHA-256 over UTF-8 text joined with a bar, `|`, as lower-case hex. The contract computes it with "
        "Python's `hashlib`, the site with the browser's SubtleCrypto, and both are tested against the same vectors "
        "(`tests/vectors.json`): `tests/test_static.py` checks the contract and runs `web/scripts/check-vectors.mjs` for "
        "the site.",
        "",
        "```text",
        "seal = sha256(text + \"|\" + salt + \"|\" + lower_case(address))",
        "```",
        "",
        "- **The address is in the seal**, in lower case with its `0x`, so a seal copied from the other side can never be "
        "opened: the copier's address gives a different hash.",
        "- **The text may hold a bar.** The salt cannot, and the address is hex, so the joined string splits from the right "
        "one way only.",
        "- **The salt** is 8 to 80 letters, digits or dashes. The site uses `crypto.randomUUID()`.",
        "- **Exactly the bytes.** The contract hashes what it is sent, without trimming, line breaks included. The site "
        "stores the exact text in the browser's ticket, so the open sends the same bytes.",
        "",
        "## The code",
        "",
        "{/* include: web/lib/hash.mjs */}",
        "{/* end include */}",
        "",
        "## Seal vectors",
        "",
        "| Text | Salt | Address | Seal |",
        "|---|---|---|---|",
    ]
    for v in vectors["seals"]:
        text = mdx_text(v["text"].replace("\n", "\\n").replace("|", "\\|"))
        lines.append(f"| `{text}` | `{v['salt']}` | `{v['address']}` | `{v['seal']}` |")
    lines.append("")
    return "\n".join(lines)


# -- evaluation, from eval/results.json -----------------------------------------------
TERM_NAMES = ("amount", "deliverable", "deadline", "payment", "rights", "cancellation")
SHORT = {"MATCH": "M", "DIFFER": "D", "ABSENT": "A"}


def verdict_text(verdict: str, count: int) -> str:
    if not verdict:
        return ""
    return "SAME PAGE" if verdict == "SAME_PAGE" else f"{verdict} · {count}"


def evaluation_page() -> str:
    path = ROOT / "eval" / "results.json"
    results = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {"cases": {}, "attempts": []}
    golden = json.loads((ROOT / "eval" / "golden.json").read_text(encoding="utf-8"))
    lock_path = ROOT / "eval" / "golden.lock.json"
    lock = json.loads(lock_path.read_text(encoding="utf-8")) if lock_path.exists() else {}
    explorer = results.get("explorer", "https://explorer-studio-dev.genlayer.com")
    contract = results.get("contract", "")

    def got(cid: str) -> dict:
        row = results["cases"].get(cid, {})
        return row if row.get("verdict") else {}

    main = [c for c in golden["cases"] if not c.get("held_out")]
    held = [c for c in golden["cases"] if c.get("held_out")]
    run = [c for c in main if got(c["id"])]
    all_six = sum(1 for c in run if [got(c["id"])["statuses"][t] for t in TERM_NAMES] == [c["statuses"][t] for t in TERM_NAMES])
    verdicts = sum(1 for c in run if (got(c["id"])["verdict"], got(c["id"])["count"]) == (c["verdict"], c["count"]))
    terms_hit = sum(1 for c in run for t in TERM_NAMES if got(c["id"])["statuses"][t] == c["statuses"][t])
    h_run = [c for c in held if got(c["id"])]
    h_tried = [c for c in held if any(a["case"] == c["id"] for a in results.get("attempts", []))]
    lines = [
        "---",
        "title: Evaluation results with transactions",
        "description: The golden cases and the held-out cases through real consensus on the deployed contract, reported as they came out.",
        "---",
        "",
        "{/* Generated by scripts/gen_docs.py from eval/results.json. Do not edit by hand. */}",
        "",
    ]
    if not run:
        lines += ["The golden run has not finished yet. This page is generated from `eval/results.json` once it has.", ""]
    else:
        lines += [
            "Every case below is one page on the deployed contract, "
            f"[`{contract}`]({explorer}/address/{contract}): two accounts sealed and opened by two accounts of their own, "
            "then one `check` transaction in which every validator asked the judge in both orders and agreed on all six "
            "statuses. Every status was read back from the contract with `get_page`.",
            "",
            f"- **Verdicts: {verdicts} of {len(run)}** golden cases came back with the expected verdict and count.",
            f"- **All six statuses: {all_six} of {len(run)}** golden cases matched the expected status on every term, "
            f"and **{terms_hit} of {len(run) * 6}** term statuses matched one by one. The spec scores cases on all six "
            "statuses, so that is the headline number" + (f" ({len(main) - len(run)} not run yet)." if len(run) < len(main) else "."),
            f"- **Held-out cases: {len(h_run)} of {len(h_tried)} run reached a verdict.** They were written before the first run "
            "with no expected answer, checked once after the golden results were recorded, and are shown exactly as they came "
            "out. A held-out round where the validators did not agree stored nothing and is listed as no decision; it is not "
            "sent again.",
        ]
        if lock:
            lines.append(
                f"- `eval/golden.json` was hashed and timestamped before the first run: sha256 `{lock['sha256']}`, locked at "
                f"{lock['locked_at']}. Nothing was tuned; the judge prompt is the spec's, word for word."
            )
        lines.append("")
    lines += [
        "Statuses read in term order, amount, deliverable, deadline, payment, rights, cancellation: M is MATCH, D is DIFFER, "
        "A is ABSENT.",
        "",
        "| Case | What changes | Expected | Statuses | Result | Scored | Transaction |",
        "|---|---|---|---|---|---|---|",
    ]
    for c in golden["cases"]:
        row = got(c["id"])
        tx = results["cases"].get(c["id"], {}).get("check_tx", "")
        link = f"[{tx[:10]}…]({explorer}/tx/{tx})" if tx else ""
        expected = "EITHER" if c.get("held_out") else verdict_text(c["verdict"], c["count"]) + " " + "".join(SHORT[c["statuses"][t]] for t in TERM_NAMES)
        if row:
            statuses = "".join(SHORT[row["statuses"][t]] for t in TERM_NAMES)
            result = verdict_text(row["verdict"], row["count"])
            if c.get("held_out"):
                mark = "held out"
            else:
                same = [row["statuses"][t] for t in TERM_NAMES] == [c["statuses"][t] for t in TERM_NAMES]
                misses = [t for t in TERM_NAMES if row["statuses"][t] != c["statuses"][t]]
                mark = "✓ all six" if same else "✗ " + ", ".join(misses)
            where = f"[page {row['page_id']}](/p/{row['page_id']})"
        else:
            tried = [a for a in results.get("attempts", []) if a["case"] == c["id"]]
            pid = results["cases"].get(c["id"], {}).get("page_id")
            where = f"[page {pid}](/p/{pid})" if pid else ""
            if tried and not any(a["ok"] for a in tried):
                statuses, result, mark = "", "**no decision**", "validators did not agree"
                link = f"[{tried[-1]['tx'][:10]}…]({explorer}/tx/{tried[-1]['tx']})"
            else:
                statuses, result, mark = "", "not run yet", ""
        lines.append(f"| {c['id']} {where} | {mdx_text(c['change'])} | {expected} | {statuses} | {result} | {mark} | {link} |")
    lines += ["", "## The accounts", ""]
    for c in golden["cases"]:
        lines += [
            f"**Case {c['id']}.** A: \"{mdx_text(c['a'])}\"",
            "",
            f"B: \"{mdx_text(c['b'])}\"",
            "",
        ]
        notes = got(c["id"]).get("notes", {})
        if notes:
            lines.append("Leader's notes: " + "; ".join(f"{t}: {mdx_text(n)}" for t, n in notes.items()))
            lines.append("")
    attempts = results.get("attempts", [])
    lines += ["## Every check transaction", ""]
    if attempts:
        for a in attempts:
            what = "decided, `" + mdx_text(str(a.get("returned"))) + "`" if a.get("ok") else "no decision: " + mdx_text(str(a.get("detail", ""))[:160])
            lines.append(f"- Case {a['case']}, attempt {a['attempt']}: {what} ([tx]({explorer}/tx/{a['tx']}))")
    else:
        lines.append("None yet.")
    lines += [
        "",
        "## Reproduce",
        "",
        "```bash",
        "python eval/run_golden.py            # open, seal, open and check the golden cases, then the held-out ones once",
        "python eval/run_golden.py --report   # rewrite eval/results.md",
        "```",
        "",
        "The script refuses to run if `eval/golden.json` no longer matches its locked hash, resumes where it stopped, and "
        "saves each step before printing it. Every attempt, with its transaction, is in `eval/results.json`.",
        "",
    ]
    return "\n".join(lines)


